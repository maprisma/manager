// Maprisma as a pacman package (plan: "maprisma (pacman)", docs/protocol.md "Maprisma (pacman)").
//
// Two sources: the GitHub release's tarball (checked against its .sha256) or a folder build
// (`tools/build-release.py --addons <maprisma-addons>`, which needs the signed add-ons ZIP of that
// version). A package recipe for exactly that archive is generated in the Manager's cache, built
// unprivileged with makepkg, inspected, and installed with `pkexec /usr/bin/pacman -U`. The
// commit phase starts when pkexec is launched; pacman is never signalled (it runs as root and
// can't be: only pkexec, while it still waits for the password, is ended after [JobEngine.pkexecWait]).
part of 'jobs.dart';

const pacmanPackage = 'maprisma-bin';

/// pacman's lock: held while any package manager changes the system.
const pacmanLockFile = '/var/lib/pacman/db.lck';

/// The recipe, modelled on aur-maprisma-bin/PKGBUILD: the same package name, files, dependencies,
/// provides and conflicts; the source is the one local archive with its sha256.
const _pkgbuildTemplate = r'''# Generated by Maprisma Manager @MANAGER@ for one local archive (not for the AUR).
# Modelled on aur-maprisma-bin/PKGBUILD: the same name, files, dependencies, provides and conflicts.
# @ORIGIN@
pkgname=maprisma-bin
pkgver=@VERSION@
pkgrel=@PKGREL@
pkgdesc="Map and connect your AI agents, local LLMs, MCP servers and skills"
arch=('x86_64')
url="https://maprisma.com"
license=('MIT')
depends=('gtk3' 'glib2' 'cairo' 'pango' 'harfbuzz' 'fontconfig' 'gdk-pixbuf2' 'libepoxy'
         'at-spi2-core' 'zlib' 'glibc' 'libgcc' 'libstdc++' 'curl')
optdepends=('xdg-utils: open the manual and release pages'
            'xdg-terminal-exec: start agents in your own terminal'
            'mise: install and update agents'
            'hyprland: the popup under the bar on Omarchy')
provides=('maprisma')
conflicts=('maprisma')
source=("maprisma-$pkgver-x86_64.tar.gz::@URL@")
sha256sums=('@SHA256@')
options=('!strip' '!debug')

package() {
    cd "maprisma-$pkgver"
    install -d "$pkgdir/usr/lib/maprisma"
    cp -a app/. "$pkgdir/usr/lib/maprisma/"
    install -d "$pkgdir/usr/bin"
    ln -s /usr/lib/maprisma/maprisma "$pkgdir/usr/bin/maprisma"
    install -Dm644 share/applications/com.maprisma.Maprisma.desktop -t "$pkgdir/usr/share/applications/"
    install -Dm644 share/metainfo/com.maprisma.Maprisma.metainfo.xml -t "$pkgdir/usr/share/metainfo/"
    install -Dm644 share/icons/hicolor/scalable/apps/com.maprisma.Maprisma.svg \
        -t "$pkgdir/usr/share/icons/hicolor/scalable/apps/"
    install -Dm644 LICENSE -t "$pkgdir/usr/share/licenses/$pkgname/"
}
''';

final _plainVersion = RegExp(r'^[0-9]+(\.[0-9]+){0,4}$');
final _safeUrlPath = RegExp(r'^/[A-Za-z0-9._/+-]+$');

/// The PKGBUILD for [version]-[pkgrel] from [url] (a `file://` URL) with [sha256].
String maprismaPkgbuild({required String version, required int pkgrel, required String url, required String sha256, String origin = ''}) {
  if (!_plainVersion.hasMatch(version)) throw ArgumentError.value(version, 'version');
  if (!RegExp(r'^file:///[A-Za-z0-9._/+-]+$').hasMatch(url)) throw ArgumentError.value(url, 'url');
  if (!RegExp(r'^[0-9a-f]{64}$').hasMatch(sha256)) throw ArgumentError.value(sha256, 'sha256');
  return _pkgbuildTemplate
      .replaceAll('@MANAGER@', coreVersion)
      .replaceAll('@ORIGIN@', origin.replaceAll('\n', ' '))
      .replaceAll('@VERSION@', version)
      .replaceAll('@PKGREL@', '$pkgrel')
      .replaceAll('@URL@', url)
      .replaceAll('@SHA256@', sha256);
}

/// The pkgrel for [version]: one above the installed one when that version is installed
/// (`0.14.2-3` → 4), else 1.
int nextPkgrel(String? installed, String version) {
  if (installed == null || installed.isEmpty) return 1;
  final dash = installed.lastIndexOf('-');
  if (dash < 0) return 1;
  final epochless = installed.substring(0, dash).replaceFirst(RegExp(r'^\d+:'), '');
  if (epochless != version) return 1;
  return (int.tryParse(installed.substring(dash + 1).split('.').first) ?? 0) + 1;
}

/// `pacman -Qip` → {Name, Version, Architecture, …}.
Map<String, String> parsePacmanInfo(String text) {
  final out = <String, String>{};
  for (final line in const LineSplitter().convert(text)) {
    final m = RegExp(r'^([A-Za-z][A-Za-z ]*?)\s*:\s?(.*)$').firstMatch(line);
    if (m != null) out.putIfAbsent(m.group(1)!, () => m.group(2)!.trim());
  }
  return out;
}

/// The package version without its pkgrel (`0.14.2-1` → `0.14.2`).
String? packageBaseVersion(String? v) {
  if (v == null || v.isEmpty) return null;
  final dash = v.lastIndexOf('-');
  return (dash < 0 ? v : v.substring(0, dash)).replaceFirst(RegExp(r'^\d+:'), '');
}

/// One archive to package: from a release (tag, asset, sha256, url) or a folder build.
final class _Archive {
  _Archive({required this.kind, required this.version, required this.file, required this.sha256, this.release, this.asset});
  final String kind; // release / folder
  final String version;
  final String file;
  final String sha256;
  final Map<String, dynamic>? release;
  final String? asset;
}

extension _Pacman on JobEngine {
  String get _lock => paths.sys(pacmanLockFile);

  void _checkLock() {
    if (FileSystemEntity.typeSync(_lock, followLinks: false) != FileSystemEntityType.notFound) {
      throw JobFailure('pacman_locked',
          trf('pacman\'s database is locked ({0}): another package manager runs, or one ended without removing it; nothing was changed', [pacmanLockFile]));
    }
  }

  /// A system tool the jobs run; refused when a test world (another root) would reach the real one.
  String _tool(String name) {
    final t = ctx.runner.which(name);
    if (t == null) throw JobFailure('missing_prerequisite', trf('Maprisma needs {0}', [name]));
    if (paths.root != '/' && (t.startsWith('/usr/') || t.startsWith('/bin/'))) {
      throw JobFailure('unsafe', trf('{0} would be the system\'s ({1}) with a test root ({2}): refused', [name, t, paths.root]));
    }
    return t;
  }

  Future<String?> _installedPackage() => StatusReader(ctx).pacmanVersion(pacmanPackage);

  /// Release or folder: the one asked for (`options.source`, a release job), else the newer of
  /// the latest release and the folder's version (the same version: the release).
  Future<({String kind, String version, String why})> _chooseSource(_Run r, AppEntry app) async {
    final options = r.job['options'] as Map? ?? const {};
    final asked = r.kind == JobKind.release ? 'release' : options['source'] as String?;
    String? relVersion, relError;
    if (asked != 'folder') {
      final tag = options['tag'] as String?;
      try {
        final rel = await ctx.github.release(app.mainInput.github!, tag: tag);
        if (rel != null && rel['tag'] is String) relVersion = tagVersion(rel['tag'] as String);
        if (rel == null) relError = tag == null ? tr('no release') : trf('no release {0}', [tag]);
      } on Object catch (e) {
        relError = e is GitHubError ? e.message : 'offline? ($e)';
      }
    }
    String? folderVersion;
    final folder = ctx.repoFolder(app.mainInput.repo);
    if (asked != 'release' && File(p.join(folder, 'tools/build-release.py')).existsSync()) {
      folderVersion = StatusReader(ctx).folderVersion(app);
    }
    if (asked == 'release') {
      if (relVersion == null) throw JobFailure(relError == tr('no release') || (relError ?? '').startsWith(tr('no release')) ? 'no_release' : 'github_failed', trf('the release: {0}', [relError ?? tr('unknown')]));
      return (kind: 'release', version: relVersion, why: r.kind == JobKind.release ? tr('a release job') : tr('asked for'));
    }
    if (asked == 'folder') {
      if (folderVersion == null) throw JobFailure('no_source', trf('{0} has no tools/build-release.py or no MAPRISMA_VERSION', [folder]));
      return (kind: 'folder', version: folderVersion, why: tr('asked for'));
    }
    if (relVersion != null && folderVersion != null) {
      final c = compareVersions(folderVersion, relVersion) ?? 0;
      return c > 0
          ? (kind: 'folder', version: folderVersion, why: trf('the folder ({0}) is newer than the release ({1})', [folderVersion, relVersion]))
          : (kind: 'release', version: relVersion, why: c == 0 ? trf('the release and the folder are both {0}: the release', [relVersion]) : trf('the release ({0}) is newer than the folder ({1})', [relVersion, folderVersion]));
    }
    if (relVersion != null) return (kind: 'release', version: relVersion, why: tr('no folder build possible'));
    if (folderVersion != null) return (kind: 'folder', version: folderVersion, why: trf('no release ({0})', [relError ?? tr('none')]));
    throw JobFailure('no_source', trf('neither a release ({0}) nor a folder with tools/build-release.py', [relError ?? tr('none')]));
  }

  Future<Map<String, dynamic>> _installPacman(_Run r) async {
    final app = r.app;
    final c = app.components.firstWhere((c) => c.kind == InstallKind.pacman);
    r.component = c;
    _phase(r, 'prepare', component: c);
    for (final t in ['makepkg', 'pacman', 'pkexec', if (app.units.isNotEmpty) 'systemctl']) {
      _tool(t);
    }
    final installed = await _installedPackage();
    if (installed == null) throw JobFailure('missing_prerequisite', tr('pacman not found'));
    final source = await _chooseSource(r, app);
    r.log.note(trf('source: {0} {1} ({2}); installed: {3}', [source.kind, source.version, source.why, installed.isEmpty ? tr('none') : installed]));
    if (!_plainVersion.hasMatch(source.version)) throw JobFailure('no_source', trf('version "{0}" is not a plain version', [source.version]));
    _checkCancel(r);

    if (r.kind == JobKind.update && installed.isNotEmpty) {
      final cmp = compareVersions(packageBaseVersion(installed), source.version);
      if (cmp != null && cmp >= 0) {
        r.log.note(trf('already up to date: {0} {1} (the {2} is {3})', [pacmanPackage, installed, source.kind, source.version]));
        return {'up_to_date': true, 'installed': installed, 'source': source.kind, 'version': source.version};
      }
    }

    // The inputs as they are now (a folder build reads both repos; a release names the folder).
    final inputs = <Map<String, dynamic>>[];
    for (final repo in [app.mainInput.repo, if (source.kind == 'folder') ...app.inputs.skip(1).map((i) => i.repo)]) {
      final g = await ctx.git.inspect(repo, ctx.repoFolder(repo));
      if (g.head == null) {
        if (source.kind == 'folder') throw JobFailure('no_source', '${ctx.repoFolder(repo)}: ${g.error ?? 'not a git repository with a commit'}');
        continue;
      }
      inputs.add({'repo': repo, 'commit': g.head, 'dirty': g.dirty ?? true, 'fingerprint': ?await ctx.git.fingerprint(ctx.repoFolder(repo), (f) => sha256File(f))});
    }
    final cat = catalogPaths(paths, [c]);
    r.signatures = signatures([for (final (_, path) in cat) path]);

    final _Archive archive;
    if (source.kind == 'release') {
      final rel = await _downloadRelease(r, app);
      archive = _Archive(kind: 'release', version: tagVersion(rel.release['tag'] as String), file: rel.file, sha256: rel.sha256, release: rel.release, asset: rel.asset);
    } else {
      archive = await _folderBuild(r, app, c, source.version);
    }
    if (archive.version != source.version) throw JobFailure('no_source', trf('the archive is {0}, not {1}', [archive.version, source.version]));
    _checkCancel(r);

    // The recipe and the package, unprivileged.
    final pkgrel = nextPkgrel(installed, archive.version);
    final pkg = await _buildPackage(r, c, archive, pkgrel);
    final want = '${archive.version}-$pkgrel';
    _checkCancel(r);

    // Commit: from here nothing is cancellable.
    _checkLock();
    final units = await _unitStates(app);
    _commitPacman(r, 'pkexec pacman -U');
    final int code;
    try {
      await _stopApp(r);
      code = await _pkexecPacman(r, ['-U', '--noconfirm', pkg.file]);
    } on Object {
      await _restoreUnits(r, units, enable: false);
      rethrow;
    }
    if (code != 0) {
      await _restoreUnits(r, units, enable: false);
      final failure = _pacmanFailure(r, code, 'installing $want');
      // only a failure before pacman's transaction changed nothing (pacman may have written files
      // before it failed: then repair stays offered)
      if (_beforeTransaction(failure)) r.committed = false;
      throw failure;
    }

    _phase(r, 'verify');
    final now = await _installedPackage();
    final failing = <String>[];
    if (now != want) failing.add(trf('pacman -Q {0} says {1}, not {2}', [pacmanPackage, now == null || now.isEmpty ? tr('not installed') : now, want]));
    final bundle = _bundleVersion();
    if (bundle != archive.version) failing.add(trf('/usr/lib/maprisma/data/flutter_assets/version.json says {0}, not {1}', [bundle ?? 'nothing', archive.version]));
    for (final ip in c.paths) {
      final ch = checkPath(paths, ip);
      if (ch['ok'] != true) failing.add('${ch['path']}: ${ch['problem']}');
    }
    if (failing.isNotEmpty) {
      for (final f in failing) {
        r.log.note(trf('postcondition: {0}', [f]));
      }
      await _restoreUnits(r, units, enable: false);
      throw JobFailure('verify_failed', failing.first);
    }
    r.log.note(trf('installed: {0} {1}, version.json {2}', [pacmanPackage, now, archive.version]));

    _phase(r, 'finish');
    final started = await _restoreUnits(r, units, enable: false);
    final notStarted = [for (final e in units.entries) if ((e.value.active || e.value.enabled) && !started.contains(e.key)) e.key];
    if (notStarted.isNotEmpty) (r.job['warnings'] ??= <String>[]).add(trf('not started again: {0}', [notStarted.join(', ')]));
    final receiptJson = <String, dynamic>{
      'schema': 1,
      'id': app.id,
      'at': ctx.clock().toUtc().toIso8601String(),
      'version': archive.version,
      'manager': coreVersion,
      'job': r.id,
      'kind': r.kind.name,
      'components': [c.id],
      'source': archive.kind == 'release'
          ? {'kind': 'release', 'tag': archive.release!['tag'], 'asset': archive.asset, 'sha256': archive.sha256, 'url': ?archive.release!['url']}
          : {'kind': 'folder', 'archive': {'file': archive.file, 'sha256': archive.sha256}},
      'package': {'name': pacmanPackage, 'version': want, 'file': pkg.file, 'sha256': pkg.sha256, 'recipe': pkg.recipe},
      'inputs': inputs,
      'paths': [
        for (final (_, path) in cat)
          if (pathState(path) case final st when st['exists'] == true)
            switch (st['type']) {
              'file' => {'path': path, 'sha256': st['sha256'], 'mode': st['mode']},
              'link' => {'path': path, 'link': st['link']},
              _ => {'path': path, 'dir': true},
            },
      ],
      'displaced': const [],
    };
    Receipt.parse(app.id, jsonDecode(jsonEncode(receiptJson)));
    atomicWrite(p.join(paths.receipts, '${app.id}.json'), const JsonEncoder.withIndent('  ').convert(receiptJson));
    r.log.note(tr('receipt written'));
    return {
      'version': archive.version,
      'package': {'name': pacmanPackage, 'version': want, 'file': pkg.file, 'sha256': pkg.sha256},
      'source': receiptJson['source'],
      'before': installed.isEmpty ? null : installed,
      'stopped': r.job['stopped'] ?? const [],
      if (started.isNotEmpty) 'unitsStarted': started,
      if (notStarted.isNotEmpty) 'unitsNotStarted': notStarted,
      'receipt': p.join(paths.receipts, '${app.id}.json'),
    };
  }

  String? _bundleVersion() {
    try {
      final data = jsonDecode(File(paths.sys('/usr/lib/maprisma/data/flutter_assets/version.json')).readAsStringSync());
      return data is Map && data['version'] is String ? data['version'] as String : null;
    } on Object {
      return null;
    }
  }

  /// `tools/build-release.py --addons <maprisma-addons>`: the signed add-ons of that version must
  /// exist (the Manager doesn't sign add-ons). Returns the new `dist/maprisma-<v>-x86_64.tar.gz`.
  Future<_Archive> _folderBuild(_Run r, AppEntry app, Component c, String version) async {
    for (final t in ['python3', 'flutter']) {
      if (ctx.tool(t) == null) throw JobFailure('missing_prerequisite', trf('a folder build of Maprisma needs {0}', [t]));
    }
    final folder = ctx.repoFolder(c.repo);
    final addons = ctx.repoFolder(app.inputs[1].repo);
    final zip = p.join(addons, 'dist', 'adapters-$version.zip');
    if (!File(zip).existsSync()) {
      throw JobFailure('missing_addons', trf('{0} is missing: sign the {1} add-ons first (tools/release-adapters.sh in {2}); the Manager doesn\'t sign add-ons', [zip, version, app.inputs[1].repo]));
    }
    final archive = p.join(folder, 'dist', 'maprisma-$version-x86_64.tar.gz');
    if (File(archive).existsSync()) r.log.note(trf('build-release.py replaces {0} (and its .sha256)', [archive]));
    final started = DateTime.now().subtract(const Duration(seconds: 2));
    await _runScript(r, c, argv: ['python3', 'tools/build-release.py', '--addons', addons]);
    final st = FileSystemEntity.typeSync(archive, followLinks: false) == FileSystemEntityType.file ? File(archive).statSync() : null;
    if (st == null || st.modified.isBefore(started)) throw JobFailure('build_failed', trf('build-release.py made no new {0}', [archive]));
    final sha = await sha256OfFile(archive);
    final sumFile = File('$archive.sha256');
    if (sumFile.existsSync()) {
      final want = parseSha256File(sumFile.readAsStringSync(), p.basename(archive));
      if (want != null && want != sha) throw JobFailure('checksum_mismatch', trf('{0}: sha256 {1}, its .sha256 says {2}', [archive, sha, want]));
    }
    r.log.note(trf('built {0} (sha256 {1})', [archive, sha]));
    return _Archive(kind: 'folder', version: version, file: archive, sha256: sha);
  }

  /// The recipe in `~/.cache/maprisma-manager/pkg/<version>/` (made afresh), makepkg there, the
  /// package checked (name, version, arch, its key files).
  Future<({String file, String sha256, String recipe})> _buildPackage(_Run r, Component c, _Archive a, int pkgrel) async {
    final base = p.join(paths.cache, 'maprisma-manager', 'pkg');
    final dir = p.join(base, a.version);
    for (final d in [p.join(paths.cache, 'maprisma-manager'), base, dir]) {
      if (FileSystemEntity.typeSync(d, followLinks: false) == FileSystemEntityType.link) throw JobFailure('unsafe', trf('{0} is a link: not used', [d]));
    }
    if (Directory(dir).existsSync()) Directory(dir).deleteSync(recursive: true);
    Directory(dir).createSync(recursive: true);
    var src = a.file;
    if (!_safeUrlPath.hasMatch(src)) {
      // a path makepkg's URL can't carry as it is: a copy in the recipe folder
      src = p.join(dir, 'in', p.basename(a.file).replaceAll(RegExp(r'[^A-Za-z0-9._+-]'), '_'));
      Directory(p.dirname(src)).createSync();
      File(a.file).copySync(src);
    }
    final origin = a.kind == 'release' ? trf('Source: release {0} ({1})', [a.release!['tag'], a.asset]) : tr('Source: a build of the maprisma folder');
    final recipe = p.join(dir, 'PKGBUILD');
    File(recipe).writeAsStringSync(maprismaPkgbuild(version: a.version, pkgrel: pkgrel, url: 'file://$src', sha256: a.sha256, origin: origin));
    r.log.note(trf('recipe: {0} ({1} {2}-{3} from {4})', [recipe, pacmanPackage, a.version, pkgrel, src]));
    final env = {
      'PKGDEST': dir,
      'SRCDEST': dir,
      'SRCPKGDEST': dir,
      'LOGDEST': dir,
      'BUILDDIR': p.join(dir, 'build'),
    };
    // Only runtime dependencies (no makedepends): pacman checks them when it installs.
    await _runScript(r, c, argv: ['makepkg', '--nodeps', '--noconfirm', '--cleanbuild', '--force', '--noprogressbar'], cwd: dir, extraEnv: env);
    final list = await ctx.runner.run(['makepkg', '--packagelist'], cwd: dir, extraEnv: {...env, 'LC_ALL': 'C'});
    final file = const LineSplitter()
        .convert(list.stdout)
        .map((l) => l.trim())
        .where((l) => l.isNotEmpty && p.isWithin(dir, l) && File(l).existsSync())
        .firstOrNull;
    if (file == null) throw JobFailure('build_failed', trf('makepkg made no package in {0}', [dir]));
    final info = await ctx.runner.run(['pacman', '-Qip', file], extraEnv: const {'LC_ALL': 'C'});
    final fields = parsePacmanInfo(info.stdout);
    final want = '${a.version}-$pkgrel';
    if (!info.ok || fields['Name'] != pacmanPackage || fields['Version'] != want || fields['Architecture'] != 'x86_64') {
      throw JobFailure('bad_package', trf('{0} is {1} {2} {3}, not {4} {5} x86_64', [file, fields['Name'] ?? '?', fields['Version'] ?? '?', fields['Architecture'] ?? '?', pacmanPackage, want]));
    }
    final files = await ctx.runner.run(['pacman', '-Qlp', file], extraEnv: const {'LC_ALL': 'C'}, timeout: const Duration(seconds: 60));
    final listed = {for (final l in const LineSplitter().convert(files.stdout)) l.trim().split(' ').last};
    for (final need in ['/usr/lib/maprisma/maprisma', '/usr/lib/maprisma/lib/maprisma-core', '/usr/bin/maprisma']) {
      if (!listed.contains(need)) throw JobFailure('bad_package', trf('{0} has no {1}', [file, need]));
    }
    final sha = await sha256OfFile(file);
    r.log.note(trf('package: {0} ({1} {2} x86_64, {3} entries, sha256 {4})', [file, pacmanPackage, want, listed.length, sha]));
    r.job['package'] = {'file': file, 'sha256': sha, 'version': want};
    _persist(r.job);
    return (file: file, sha256: sha, recipe: recipe);
  }

  /// The app's systemd user units: active and enabled now (to put back as they were).
  Future<Map<String, ({bool active, bool enabled})>> _unitStates(AppEntry app) async {
    final out = <String, ({bool active, bool enabled})>{};
    if (ctx.runner.which('systemctl') == null) return out;
    for (final u in app.units) {
      final a = await ctx.runner.run(['systemctl', '--user', 'is-active', '--quiet', u.name], timeout: const Duration(seconds: 10));
      final e = await ctx.runner.run(['systemctl', '--user', 'is-enabled', '--quiet', u.name], timeout: const Duration(seconds: 10));
      out[u.name] = (active: a.ok, enabled: e.ok);
    }
    return out;
  }

  /// Starts (and with [enable] enables again) the units that were active or enabled before.
  Future<List<String>> _restoreUnits(_Run r, Map<String, ({bool active, bool enabled})> units, {required bool enable}) async {
    final started = <String>[];
    for (final e in units.entries) {
      if (enable && e.value.enabled) {
        final s = await ctx.runner.run(['systemctl', '--user', 'enable', e.key], timeout: const Duration(seconds: 60));
        r.log.note(trf('systemctl --user enable {0}: {1}', [e.key, s.ok ? tr('ok') : trf('failed ({0})', [s.stderr.trim()])]));
      }
      if (!e.value.active && !e.value.enabled) continue;
      final s = await ctx.runner.run(['systemctl', '--user', 'start', e.key], timeout: const Duration(seconds: 60));
      r.log.note(trf('systemctl --user start {0}: {1}', [e.key, s.ok ? tr('ok') : trf('failed ({0})', [s.stderr.trim()])]));
      if (s.ok) started.add(e.key);
    }
    return started;
  }

  void _commitPacman(_Run r, String what) {
    r.committed = true;
    r.job['committed'] = true;
    r.job['phase'] = 'commit';
    _persist(r.job);
    r.log.note(trf('phase: commit ({0}; not cancellable from here)', [what]));
  }

  /// The password dialog or pacman's lock refused: pacman changed nothing.
  bool _beforeTransaction(JobFailure f) => const {'auth_cancelled', 'auth_timeout', 'pacman_locked'}.contains(f.code);

  JobFailure _pacmanFailure(_Run r, int code, String what) {
    final out = r.recent.toString();
    if (code == -126) return JobFailure('auth_timeout', trf('the password dialog was not answered within {0} s: {1} not started; nothing was changed', [pkexecWait.inSeconds, what]));
    if (code == 126 || code == 127) return JobFailure('auth_cancelled', trf('authentication was cancelled or refused (pkexec exit {0}): {1} not started; nothing was changed', [code, what]));
    if (out.contains('unable to lock database')) return JobFailure('pacman_locked', trf('pacman\'s database is locked ({0}): nothing was changed', [pacmanLockFile]));
    return JobFailure('pacman_failed', trf('pacman failed (exit {0}) {1}: repair (reinstall) when files were changed', [code, what]));
  }

  /// `pkexec /usr/bin/pacman <args>`: pkexec shows the password dialog, then becomes pacman (the
  /// same pid; its name changes). While it is still pkexec after [pkexecWait] it is ended (the
  /// dialog goes away; exit -126). pacman itself is never signalled (it runs as root). Output to
  /// the log. Returns the exit code.
  Future<int> _pkexecPacman(_Run r, List<String> args) async {
    final pk = _tool('pkexec');
    r.log.note(trf('\$ pkexec /usr/bin/pacman {0}   (a password dialog asks for the administrator password)', [args.join(' ')]));
    r.recent.clear();
    final Process proc;
    try {
      proc = await Process.start(pk, ['/usr/bin/pacman', ...args],
          environment: scriptEnv(const Component(id: 'pkexec', name: 'pkexec', repo: '', install: [], paths: []), job: r.id),
          includeParentEnvironment: false,
          workingDirectory: paths.home);
    } on ProcessException catch (e) {
      throw JobFailure('pacman_failed', trf('pkexec could not start: {0}', [e.message]));
    }
    r.job['pkexec'] = {'pid': proc.pid, 'start': procStat(proc.pid)?.start};
    _persist(r.job);
    await proc.stdin.close();
    void out(List<int> d) {
      r.log.add(d);
      r.remember(d);
    }

    final outDone = proc.stdout.listen(out).asFuture<void>();
    final errDone = proc.stderr.listen(out).asFuture<void>();
    var exited = false;
    final code = proc.exitCode.then((c) {
      exited = true;
      return c;
    });
    final until = DateTime.now().add(pkexecWait);
    var authenticated = false;
    var ended = false;
    String? name() {
      try {
        return File('/proc/${proc.pid}/comm').readAsStringSync().trim();
      } on FileSystemException {
        return null;
      }
    }

    var lastNote = DateTime.now();
    while (!exited) {
      await Future.any([code, Future<void>.delayed(const Duration(milliseconds: 250))]);
      if (exited) break;
      if (!authenticated) {
        final n = name();
        if (n != null && n != 'pkexec') {
          authenticated = true;
          r.log.note(trf('authenticated: {0} runs', [n]));
        } else if (DateTime.now().isAfter(until)) {
          // still pkexec (asking): ended; a pacman it has become meanwhile runs as root and can't be signalled
          if (name() == 'pkexec') {
            proc.kill(ProcessSignal.sigterm);
            ended = true;
            r.log.note(trf('no answer to the password dialog within {0} s: pkexec ended', [pkexecWait.inSeconds]));
            break;
          }
        }
      } else if (DateTime.now().difference(lastNote) > const Duration(minutes: 1)) {
        lastNote = DateTime.now();
        r.log.note(tr('pacman still runs (it is never interrupted)'));
      }
    }
    final c = await code;
    try {
      await Future.wait([outDone, errDone]).timeout(const Duration(seconds: 2));
    } on TimeoutException {
      // a child holds the output
    }
    r.log.note(trf('pkexec exit code {0}', [c]));
    return ended && !authenticated ? -126 : c;
  }

  Future<Map<String, dynamic>> _removePacman(_Run r) async {
    final app = r.app;
    final options = r.job['options'] as Map<String, dynamic>;
    _phase(r, 'prepare');
    final plan = await removePlan(ctx, app, deleteSettings: options['delete_settings'] == true);
    r.job['plan'] = {'revision': plan.revision, 'goes': plan.goes.length};
    if (options['revision'] != null && options['revision'] != plan.revision) {
      throw JobFailure('changed', tr('what would be removed changed since the plan was shown'));
    }
    final dependents = plan.json['dependents'] as List;
    if (dependents.isNotEmpty && options['dependents_ok'] != true) {
      throw JobFailure('needed_by', trf('needed by {0}', [dependents.map((d) => d['name']).join(', ')]));
    }
    if (plan.blocked != null) throw JobFailure('blocked', plan.blocked!);
    _tool('pkexec');
    if (app.units.isNotEmpty) _tool('systemctl');
    final installed = await _installedPackage();
    _checkCancel(r);
    _checkLock();

    final units = await _unitStates(app);
    _commitPacman(r, 'pkexec pacman -R');
    for (final e in units.entries) {
      if (e.value.active) {
        final s = await ctx.runner.run(['systemctl', '--user', 'stop', e.key], timeout: const Duration(seconds: 60));
        r.log.note(trf('systemctl --user stop {0}: {1}', [e.key, s.ok ? tr('ok') : trf('failed ({0})', [s.stderr.trim()])]));
      }
      if (e.value.enabled) {
        final s = await ctx.runner.run(['systemctl', '--user', 'disable', e.key], timeout: const Duration(seconds: 60));
        r.log.note(trf('systemctl --user disable {0}: {1}', [e.key, s.ok ? tr('ok') : trf('failed ({0})', [s.stderr.trim()])]));
      }
    }
    final int code;
    try {
      await _stopApp(r);
      code = await _pkexecPacman(r, ['-R', '--noconfirm', pacmanPackage]);
    } on Object {
      await _restoreUnits(r, units, enable: true);
      rethrow;
    }
    if (code != 0) {
      await _restoreUnits(r, units, enable: true);
      final failure = _pacmanFailure(r, code, 'removing $pacmanPackage');
      if (_beforeTransaction(failure)) r.committed = false;
      throw failure;
    }

    _phase(r, 'verify');
    final now = await _installedPackage();
    if (now != null && now.isNotEmpty) throw JobFailure('verify_failed', trf('pacman -Q {0} still says {1}', [pacmanPackage, now]));

    final reach = sharedRoots(paths);
    final settings = <String>[];
    for (final path in plan.settingsGo) {
      if (unsafeReach(path, reach) != null) continue;
      final t = FileSystemEntity.typeSync(path, followLinks: false);
      if (t == FileSystemEntityType.link) {
        Link(path).deleteSync();
      } else if (t == FileSystemEntityType.directory) {
        Directory(path).deleteSync(recursive: true);
      } else if (t != FileSystemEntityType.notFound) {
        File(path).deleteSync();
      }
      settings.add(path);
      r.log.note(trf('deleted settings {0}', [path]));
    }

    _phase(r, 'finish');
    final receipt = File(p.join(paths.receipts, '${app.id}.json'));
    if (receipt.existsSync()) receipt.deleteSync();
    r.log.note(tr('receipt dropped'));
    return {
      'removed': {'name': pacmanPackage, 'version': installed},
      'units': {for (final e in units.entries) e.key: {'wasActive': e.value.active, 'wasEnabled': e.value.enabled}},
      'settingsDeleted': settings,
      'stopped': r.job['stopped'] ?? const [],
    };
  }
